-- ---------------------------------------------------------------------
-- 1. riwayat_kuis.id harus terisi otomatis
--    Di struktur yang dikirim, kolom ini "bigint not null" tanpa default,
--    sehingga insert dari aplikasi (yang tidak mengirim id) akan gagal.
-- ---------------------------------------------------------------------
do $$
begin
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'riwayat_kuis' and column_name = 'id'
          and (is_identity = 'YES' or column_default is not null)
    ) then
        alter table public.riwayat_kuis alter column id add generated by default as identity;
        perform setval(
            pg_get_serial_sequence('public.riwayat_kuis', 'id'),
            coalesce((select max(id) from public.riwayat_kuis), 0) + 1,
            false
        );
    end if;
end $$;


-- ---------------------------------------------------------------------
-- 2. Perbaiki data kota yang salah tersimpan
--    Formulir lama menampilkan "Semarang" tetapi menyimpan "Surabaya".
--    Semua "Surabaya" di data ini sebenarnya adalah responden Semarang.
-- ---------------------------------------------------------------------
update public.profiles set kota = 'Semarang' where kota = 'Surabaya';

alter table public.profiles drop constraint if exists profiles_kota_check;
alter table public.profiles
    add constraint profiles_kota_check
    check (kota is null or kota in ('Ternate', 'Palembang', 'Semarang')) not valid;
-- Jika nanti ada kota baru, jalankan ulang dua baris di atas dengan daftar kota yang baru.


-- ---------------------------------------------------------------------
-- 3. total_poin tidak boleh kosong, tanggal lahir harus masuk akal
-- ---------------------------------------------------------------------
update public.profiles set total_poin = 0 where total_poin is null;
alter table public.profiles alter column total_poin set default 0;
alter table public.profiles alter column total_poin set not null;

alter table public.profiles drop constraint if exists profiles_tanggal_lahir_check;
alter table public.profiles
    add constraint profiles_tanggal_lahir_check
    check (tanggal_lahir is null or tanggal_lahir >= date '1940-01-01') not valid;


-- ---------------------------------------------------------------------
-- 4. buku.id_kuis_terkait: text -> uuid yang benar-benar menunjuk ke buku
-- ---------------------------------------------------------------------
do $$
begin
    if (select data_type from information_schema.columns
        where table_schema = 'public' and table_name = 'buku' and column_name = 'id_kuis_terkait') = 'text' then

        -- Kosongkan nilai yang bukan uuid atau menunjuk ke buku yang sudah tidak ada
        update public.buku b set id_kuis_terkait = null
        where id_kuis_terkait is not null
          and (
              trim(id_kuis_terkait) !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
              or not exists (select 1 from public.buku x where x.id::text = trim(b.id_kuis_terkait))
          );

        alter table public.buku
            alter column id_kuis_terkait type uuid using nullif(trim(id_kuis_terkait), '')::uuid;
    end if;
end $$;

alter table public.buku drop constraint if exists buku_id_kuis_terkait_fkey;
alter table public.buku
    add constraint buku_id_kuis_terkait_fkey
    foreign key (id_kuis_terkait) references public.buku (id) on delete set null;


