-- ---------------------------------------------------------------------
-- 6. Profil otomatis terisi dari data pendaftaran
--    Aplikasi mengirim nama, jenis kelamin, kategori, kota, dan tanggal
--    lahir sebagai metadata saat daftar. Trigger ini menyalinnya ke
--    profiles, sehingga data tetap tersimpan walaupun "Confirm email"
--    aktif (saat itu aplikasi belum punya sesi login untuk menulis sendiri).
--    Nama trigger diawali "zz_" agar berjalan SETELAH trigger lama Anda,
--    dan memakai ON CONFLICT sehingga tidak bentrok dengannya.
-- ---------------------------------------------------------------------
create or replace function public.isi_profil_dari_metadata()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
    tgl date := case
        when (m->>'tanggal_lahir') ~ '^\d{4}-\d{2}-\d{2}$' then (m->>'tanggal_lahir')::date
        else null
    end;
begin
    insert into public.profiles (id, nama_lengkap, jenis_kelamin, kategori, kota, tanggal_lahir, total_poin)
    values (
        new.id,
        coalesce(nullif(trim(m->>'nama_lengkap'), ''), split_part(new.email, '@', 1)),
        case when m->>'jenis_kelamin' in ('Laki-laki', 'Perempuan') then m->>'jenis_kelamin' end,
        case when m->>'kategori' in ('Pelajar', 'Mahasiswa', 'Umum') then m->>'kategori' end,
        case when m->>'kota' in ('Ternate', 'Palembang', 'Semarang') then m->>'kota' end,
        tgl,
        0
    )
    on conflict (id) do update set
        nama_lengkap  = coalesce(nullif(trim(m->>'nama_lengkap'), ''), public.profiles.nama_lengkap),
        jenis_kelamin = coalesce(excluded.jenis_kelamin, public.profiles.jenis_kelamin),
        kategori      = coalesce(excluded.kategori, public.profiles.kategori),
        kota          = coalesce(excluded.kota, public.profiles.kota),
        tanggal_lahir = coalesce(excluded.tanggal_lahir, public.profiles.tanggal_lahir);
    return new;
end;
$$;

drop trigger if exists zz_isi_profil_dari_metadata on auth.users;
create trigger zz_isi_profil_dari_metadata
    after insert on auth.users
    for each row execute function public.isi_profil_dari_metadata();


